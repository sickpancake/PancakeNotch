import AppKit
import Foundation
import Testing
@testable import ModuleShelf

@MainActor
@Suite struct ShelfClipboardTests {
    let folder = FileManager.default.temporaryDirectory.appending(path: "ShelfClipboardTests-\(UUID().uuidString)", directoryHint: .isDirectory)

    func pasteboard() -> NSPasteboard { NSPasteboard(name: .init("ShelfClipboardTests-\(UUID().uuidString)")) }

    func pngData(width: Int = 4, height: Int = 4) -> Data {
        let rep = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: width, pixelsHigh: height, bitsPerSample: 8,
                                   samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                                   bytesPerRow: 0, bitsPerPixel: 0)!
        return rep.representation(using: .png, properties: [:])!
    }

    @Test func readsTextAndLinks() {
        let board = pasteboard()
        board.clearContents()
        board.setString("hello world", forType: .string)
        #expect(ShelfClipboardReader.read(board) == .input(.text("hello world")))
        board.clearContents()
        board.setString("  https://example.com/a  ", forType: .string)
        #expect(ShelfClipboardReader.read(board) == .input(.link(URL(string: "https://example.com/a")!)))
        board.clearContents()
        board.setString("   ", forType: .string)
        #expect(ShelfClipboardReader.read(board) == .skipped)
    }

    @Test(arguments: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"])
    func skipsPrivateCopies(type: String) {
        let board = pasteboard()
        board.declareTypes([.string, NSPasteboard.PasteboardType(type)], owner: nil)
        board.setString("hunter2", forType: .string)
        board.setData(Data(), forType: NSPasteboard.PasteboardType(type))
        #expect(ShelfClipboardReader.read(board) == .skipped)
    }

    @Test func skipsCopiedFilesAndReadsImages() {
        let board = pasteboard()
        board.clearContents()
        board.writeObjects([URL(fileURLWithPath: "/tmp") as NSURL])
        #expect(ShelfClipboardReader.read(board) == .skipped)
        board.clearContents()
        board.setData(pngData(), forType: .png)
        guard case .input(.image(let data)) = ShelfClipboardReader.read(board) else {
            Issue.record("expected an image")
            return
        }
        #expect(NSImage(data: data) != nil)
    }

    @Test func scalesDownHugeImages() throws {
        let png = try #require(ShelfClipboardReader.compressedImage(pngData(width: 4096, height: 1024)))
        let rep = try #require(NSBitmapImageRep(data: png))
        #expect(rep.pixelsWide == 2048)
        #expect(rep.pixelsHigh == 512)
    }

    @Test func tooLongTextIsTooLarge() {
        #expect(ShelfClipboardReader.classify(String(repeating: "a", count: ShelfClipboardReader.maxTextLength + 1)) == .tooLarge)
    }

    @Test func dedupesByMovingToFront() {
        let clipboard = ShelfClipboard(directory: folder, pasteboard: pasteboard())
        clipboard.record(.text("a"))
        clipboard.record(.text("b"))
        clipboard.record(.text("a"))
        #expect(clipboard.entries.map(\.item.displayName) == ["a", "b"])
        let image = pngData()
        clipboard.record(.image(image))
        clipboard.record(.image(image))
        #expect(clipboard.entries.count == 3)
    }

    @Test func keepsHistoryLengthButNotPinned() {
        let clipboard = ShelfClipboard(directory: folder, pasteboard: pasteboard(), length: 3)
        let first = clipboard.record(.text("1"))!
        clipboard.togglePin(first.id)
        for n in 2...6 { clipboard.record(.text("\(n)")) }
        #expect(clipboard.entries.map(\.item.displayName) == ["6", "5", "4", "1"])
        clipboard.length = 1
        #expect(clipboard.entries.map(\.item.displayName) == ["6", "1"])
        clipboard.removeAll()
        #expect(clipboard.entries.map(\.item.displayName) == ["1"])
    }

    @Test func imageFilesGoWhenEntriesDo() throws {
        let clipboard = ShelfClipboard(directory: folder, pasteboard: pasteboard(), length: 1)
        let entry = try #require(clipboard.record(.image(pngData())))
        let url = try #require(clipboard.fileURL(for: entry))
        #expect(url.path.hasPrefix(folder.path))
        clipboard.record(.text("newer"))
        #expect(!FileManager.default.fileExists(atPath: url.path))
    }

    @Test func pollsOnlyWhileRunningAndForgetsWhenTurnedOff() {
        let board = pasteboard()
        let clipboard = ShelfClipboard(directory: folder, pasteboard: board)
        board.clearContents()
        board.setString("before", forType: .string)
        clipboard.setRunning(true)
        clipboard.poll()
        #expect(clipboard.entries.isEmpty)
        board.clearContents()
        board.setString("after", forType: .string)
        clipboard.poll()
        #expect(clipboard.entries.map(\.item.displayName) == ["after"])
        clipboard.setRunning(false)
        #expect(clipboard.entries.isEmpty)
    }

    @Test func followsSettings() async {
        let defaults = UserDefaults(suiteName: "ShelfClipboardTests-\(UUID().uuidString)")!
        let settings = ShelfSettings(defaults: defaults)
        #expect(!settings.remembersCopies)
        #expect(settings.clipboardLength == 10)
        let clipboard = ShelfClipboard(directory: folder, pasteboard: pasteboard())
        clipboard.follow(settings)
        #expect(!clipboard.isRunning)
        settings.remembersCopies = true
        settings.clipboardLength = 5
        await Task.yield()
        await Task.yield()
        #expect(clipboard.isRunning)
        #expect(clipboard.length == 5)
        clipboard.setRunning(false)
    }
}
